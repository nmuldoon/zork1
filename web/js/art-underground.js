  function rng(seed) { let s = seed * 9301 + 49297; return () => (s = (s * 9301 + 49297) % 233280) / 233280; }
  function chamber(ctx, opts) {
    const W = 44, H = 11, r = rng(ctx.id);
    const g = Array.from({ length: H }, (_, y) => Array.from({ length: W }, (_, x) =>
      (y === 0 || y === H - 1 || x < 2 || x >= W - 2) ? opts.wall : ' '));
    const has = d => ctx.exits.some(e => e.dir.name === d);
    const clear = (x0, y0, w, h) => { for (let y = y0; y < y0 + h; y++) for (let x = x0; x < x0 + w; x++) if (g[y] && g[y][x] !== undefined) g[y][x] = ' '; };
    if (has('N')) clear(19, 0, 6, 1);
    if (has('S')) clear(19, H - 1, 6, 1);
    if (has('W')) clear(0, 4, 2, 3);
    if (has('E')) clear(W - 2, 4, 2, 3);
    if (has('NW')) clear(0, 0, 5, 2);
    if (has('NE')) clear(W - 5, 0, 5, 2);
    if (has('SW')) clear(0, H - 2, 5, 2);
    if (has('SE')) clear(W - 5, H - 2, 5, 2);
    // Scatter inner rock so every chamber looks different.
    for (let i = 0; i < opts.rocks; i++) {
      const x = 4 + Math.floor(r() * (W - 8)), y = 2 + Math.floor(r() * (H - 4));
      const len = 1 + Math.floor(r() * 4);
      for (let k = 0; k < len; k++) if (g[y][x + k] === ' ') g[y][x + k] = opts.inner;
    }
    const write = (x, y, s) => { for (let i = 0; i < s.length; i++) g[y][x + i] = s[i]; };
    if (has('Up')) write(4, 2, 'H up');
    if (has('Down')) write(W - 12, H - 3, 'O down');
    const label = opts.label(ctx);
    write(Math.floor((W - label.length) / 2), Math.floor(H / 2), label);
    return { pal: opts.pal, art: g.map(row => row.join('')).join('\n') };
  }
